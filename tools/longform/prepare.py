"""Reproduce a production's explicit checked sources and declarative graphics."""
import hashlib
import json
import pathlib
import sys
import urllib.request

import longform as L
import graphics


def prepare(path):
    b=L.load(path);root=pathlib.Path(b['_dir'])
    manifest=json.loads((root/'media-manifest.json').read_text())
    for m in manifest:
        dest=(root/m['file']).resolve()
        if not dest.is_relative_to(root):raise ValueError('asset path escapes production')
        dest.parent.mkdir(parents=True,exist_ok=True)
        if dest.exists() and L.digest(dest)==m['sha256']:continue
        if not m['url'].startswith('https://'):raise ValueError('HTTPS source required')
        tmp=dest.with_suffix('.download')
        try:
            with urllib.request.urlopen(urllib.request.Request(m['url'],headers={'User-Agent':'AnimationFactory/1.0'}),timeout=120) as r,tmp.open('wb') as f:
                total=0
                while chunk:=r.read(1024*1024):
                    total+=len(chunk)
                    if total>250_000_000:raise ValueError('source too large')
                    f.write(chunk)
            if L.digest(tmp)!=m['sha256']:raise ValueError('download hash differs: '+m['file'])
            tmp.replace(dest)
        finally:tmp.unlink(missing_ok=True)
    diagram_file=root/'graphics.json'
    specs=json.loads(diagram_file.read_text()) if diagram_file.exists() else []
    for s in specs:graphics.render(s,root)
    # This generated lock binds the exact downloaded/generated bytes for this run.
    (root/'sources.lock.json').unlink(missing_ok=True)
    lock=L.footage.lock(L.flattened(b))
    for m in manifest:
        src='local:'+m['file']
        if src in lock:lock[src].update({'author':m['author'],'license':m['license'],'pageUrl':m['pageUrl'],'downloadUrl':m['url']})
    for s in specs:
        src='local:'+s['file']
        if src in lock:lock[src].update({'author':'Animation Factory','license':'Original explanatory animation; schematic, not to scale'})
    L.write_json(root/'sources.lock.json',lock)
    print('prepared',len(lock),'locked sources')


if __name__=='__main__':prepare(sys.argv[1])
